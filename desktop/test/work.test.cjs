'use strict';
const test = require('node:test'), assert = require('node:assert/strict');
const fs = require('node:fs/promises'), os = require('node:os'), path = require('node:path');
const { consume, WorkTracker } = require('../src/work.cjs');
const record = (type, payload) => ({ timestamp: new Date().toISOString(), type, payload });
test('task lifecycle exposes public commentary and explicit steps only', () => {
  const task = { calls: [], updatedAt: 0 };
  const event = (type, fields = {}) => consume(task, record('event_msg', { type, ...fields }));
  const response = payload => consume(task, record('response_item', payload));
  event('task_started', { turn_id: 'current' });
  response({ type: 'message', role: 'user', content: [{ text: 'private user message' }] });
  response({ type: 'reasoning', summary: [{ text: 'private reasoning' }] });
  assert.equal(task.detail, ''); assert.equal(task.planTotal, 0);
  response({ type: 'message', role: 'assistant', phase: 'commentary', content: [{ text: '正在验证界面' }] });
  assert.equal(task.detail, '正在验证界面');
  response({ type: 'function_call', name: 'exec_command', call_id: 'a', arguments: 'secret arguments' });
  assert.equal(task.stage, '执行工具');
  response({ type: 'function_call_output', call_id: 'a', output: 'secret result' });
  assert.equal(task.stage, '进行中');
  event('plan_updated', { plan: [{ step: '分析', status: 'completed' }, { step: '验证', status: 'in_progress' }] });
  assert.equal(task.planDone, 1); assert.equal(task.planTotal, 2); assert.equal(task.detail, '验证');
  event('task_complete', { turn_id: 'old' }); assert.equal(task.active, true);
  event('task_complete', { turn_id: 'current' }); assert.equal(task.active, false); assert.equal(task.stage, '已完成');
  event('task_started', { turn_id: 'next' }); assert.equal(task.planTotal, 0); assert.equal(task.detail, '');
  event('turn_aborted', { turn_id: 'next' }); assert.equal(task.stage, '已中断');
  assert.ok(!JSON.stringify(task).includes('secret'));
});
test('incremental JSONL handles partial UTF8, titles, completion and truncation', async t => {
  const home = await fs.mkdtemp(path.join(os.tmpdir(), 'meter-work-test-')); t.after(() => fs.rm(home, { recursive: true, force: true }));
  const dir = path.join(home, 'sessions', '2026'); await fs.mkdir(dir, { recursive: true });
  await fs.writeFile(path.join(home, 'session_index.jsonl'), JSON.stringify({ id: 'test-id', thread_name: '测试任务' }) + '\n');
  const file = path.join(dir, 'session.jsonl');
  const data = [record('session_meta', { id: 'test-id' }), record('event_msg', { type: 'task_started', turn_id: 't' }), record('response_item', { type: 'message', role: 'assistant', phase: 'commentary', content: [{ text: '中文进度' }] })].map(x => JSON.stringify(x)).join('\n') + '\n';
  const buffer = Buffer.from(data), cut = buffer.indexOf(Buffer.from('中文进度')) + 1;
  await fs.writeFile(file, buffer.subarray(0, cut));
  const tracker = new WorkTracker(home); let work = await tracker.scan();
  assert.equal(work.activeCount, 1); assert.equal(work.tasks[0].title, '测试任务'); assert.equal(work.tasks[0].detail, '');
  await fs.appendFile(file, buffer.subarray(cut)); work = await tracker.scan();
  assert.equal(work.tasks[0].detail, '中文进度');
  await fs.appendFile(file, JSON.stringify(record('event_msg', { type: 'task_complete', turn_id: 't' })) + '\n');
  work = await tracker.scan(); assert.equal(work.state, 'idle'); assert.equal(work.tasks[0].stage, '已完成');
  await fs.writeFile(file, ''); work = await tracker.scan(); assert.equal(work.activeCount, 0); assert.equal(work.tasks.length, 0);
});
