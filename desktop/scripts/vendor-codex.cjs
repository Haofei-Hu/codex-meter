'use strict';
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const { createRequire } = require('node:module');
if (process.platform !== 'win32') throw new Error('Build the Windows runtime on Windows');
const root = path.resolve(__dirname,'..'), required = createRequire(path.join(root,'vendor-package','package.json'));
const target = process.arch === 'arm64' ? 'aarch64-pc-windows-msvc' : 'x86_64-pc-windows-msvc';
const platformPackage = process.arch === 'arm64' ? '@openai/codex-win32-arm64' : '@openai/codex-win32-x64';
const cliVersion = required('@openai/codex/package.json').version;
if (cliVersion !== '0.164.0') throw new Error('Unexpected Codex runtime version');
const codexRequire = createRequire(required.resolve('@openai/codex/package.json'));
const nativeRoot = path.dirname(codexRequire.resolve(platformPackage + '/package.json'));
const vendor = path.join(nativeRoot,'vendor',target), destination = path.join(root,'vendor','codex');
if (!fs.existsSync(path.join(vendor,'bin','codex.exe'))) throw new Error('Official Windows Codex executable is missing');
fs.mkdirSync(destination,{recursive:true});
fs.cpSync(vendor,path.join(destination,target),{recursive:true,dereference:false});
for (const name of ['codex-LICENSE.txt','codex-NOTICE.txt']) fs.copyFileSync(path.join(root,'third-party',name),path.join(destination,name));
const hash = crypto.createHash('sha256').update(fs.readFileSync(path.join(vendor,'bin','codex.exe'))).digest('hex');
fs.writeFileSync(path.join(destination,'runtime.json'),JSON.stringify({package:'@openai/codex',version:cliVersion,target,license:'Apache-2.0',sha256:hash},null,2)+'\n');
console.log('Prepared official Codex runtime',cliVersion,target,'(no login or credentials included)');
